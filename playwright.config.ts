import { defineConfig, devices } from '@playwright/test';

import { FAKE_CAMERA_VIDEO } from './e2e/support/camera';

/**
 * The Cognito app client only allows http://localhost:4200/ as a callback, so
 * the app must be served on exactly this origin for any test that signs in.
 */
const baseURL = 'http://localhost:4200';
const ci = !!process.env['CI'];

export default defineConfig({
  testDir: './e2e',
  // `.e2e.ts`, not `.spec.ts`: `ng test` picks up `**/*.spec.ts` from the project root.
  testMatch: '**/*.e2e.ts',
  fullyParallel: true,
  forbidOnly: ci,
  retries: ci ? 2 : 0,
  workers: ci ? 2 : undefined,
  reporter: ci
    ? [['github'], ['html', { open: 'never' }]]
    : [['list'], ['html', { open: 'never' }]],
  use: {
    baseURL,
    trace: 'on-first-retry',
    screenshot: 'only-on-failure',
  },
  projects: [
    // Hermetic tier: the API is stubbed, nothing external is needed. This is what CI runs.
    {
      name: 'mocked',
      testIgnore: ['**/full-stack/**', '**/camera*.e2e.ts'],
      use: { ...devices['Desktop Chrome'] },
    },
    // Also hermetic, but Chromium is launched with a fake camera that films a ticket QR code, so
    // the door screen's camera scanner can be exercised. The video is generated by the setup.
    {
      name: 'mocked-camera-setup',
      testMatch: '**/camera.setup.e2e.ts',
    },
    {
      name: 'mocked-camera',
      testMatch: '**/camera-checkin.e2e.ts',
      dependencies: ['mocked-camera-setup'],
      use: {
        ...devices['Desktop Chrome'],
        permissions: ['camera'],
        launchOptions: {
          args: [
            '--use-fake-device-for-media-stream',
            '--use-fake-ui-for-media-stream',
            `--use-file-for-fake-video-capture=${FAKE_CAMERA_VIDEO}`,
          ],
        },
      },
    },
    // Full-stack tier: real Cognito sign-in and the local backend (see README). Signs each
    // test account in once, then the journey tests reuse those sessions.
    {
      name: 'full-stack-setup',
      testMatch: '**/full-stack/auth.setup.e2e.ts',
      use: { ...devices['Desktop Chrome'] },
    },
    {
      name: 'full-stack',
      testMatch: '**/full-stack/**/*.e2e.ts',
      testIgnore: '**/full-stack/auth.setup.e2e.ts',
      dependencies: ['full-stack-setup'],
      fullyParallel: false,
      timeout: 120_000,
      // Traces record request headers, which here carry real Cognito tokens.
      use: { ...devices['Desktop Chrome'], trace: 'off' },
    },
  ],
  webServer: {
    command: 'npm start',
    url: baseURL,
    reuseExistingServer: !ci,
    timeout: 120_000,
  },
});
